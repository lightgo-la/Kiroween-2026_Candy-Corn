//! UI language (English / Korean).
//!
//! UI text is written in English at the call site; the Korean translation lives in `locales/ko.json`
//! (plus `locales/ko.*.json` fragments) and is pulled in at compile time by the `ko_text!` macro that build.rs
//! generates. A missing translation is a compile error, and `format!` checks the arguments of both languages.
//! - fixed text: `tr!("Loaded")` -> `&'static str`
//! - formatted text: `trf!("{n} constraints", n = n)` -> `String` (named placeholders are passed explicitly)
//! - constant tables: `trp!("Save")` -> [`Tr`] pair, resolved later with [`Tr::get`]
//!
//! The current language is process-wide (chosen at startup: `--lang` > saved setting > English). Tests switch it
//! only for their own thread with [`with_lang`], so parallel tests never touch the global value.

use serde::{Deserialize, Serialize};
use std::cell::Cell;
use std::ffi::OsString;
use std::path::{Path, PathBuf};
use std::sync::atomic::{AtomicU8, Ordering};

// `ko_text!("English")` -> Korean string literal, generated by build.rs from locales/ko*.json.
include!(concat!(env!("OUT_DIR"), "/ko_text.rs"));

// `ko_fixture!("key")` -> Korean test input, generated by build.rs from tests/fixtures/ko.*.json.
#[cfg(test)]
include!(concat!(env!("OUT_DIR"), "/ko_fixture.rs"));

#[derive(Clone, Copy, Debug, Default, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "lowercase")]
pub enum Lang {
    Ko,
    #[default]
    En,
}

const LANG_KO: u8 = 0;
const LANG_EN: u8 = 1;

impl Lang {
    pub const ALL: [Lang; 2] = [Lang::En, Lang::Ko];

    pub fn code(self) -> &'static str {
        match self {
            Lang::Ko => "ko",
            Lang::En => "en",
        }
    }

    /// Name shown in the language picker, written in that language.
    pub fn native_name(self) -> &'static str {
        match self {
            Lang::Ko => ko_text!("Korean"),
            Lang::En => "English",
        }
    }

    pub fn parse(s: &str) -> Option<Lang> {
        match s.trim().to_ascii_lowercase().as_str() {
            "ko" | "kr" | "kor" | "korean" | "ko-kr" => Some(Lang::Ko),
            "en" | "eng" | "english" | "en-us" | "en-gb" => Some(Lang::En),
            _ if s.trim() == ko_text!("Korean") => Some(Lang::Ko),
            _ => None,
        }
    }

    fn to_u8(self) -> u8 {
        match self {
            Lang::Ko => LANG_KO,
            Lang::En => LANG_EN,
        }
    }

    fn from_u8(v: u8) -> Lang {
        if v == LANG_KO { Lang::Ko } else { Lang::En }
    }
}

/// Process-wide language; starts as the default language (English).
static GLOBAL: AtomicU8 = AtomicU8::new(LANG_EN);

thread_local! {
    static OVERRIDE: Cell<Option<Lang>> = const { Cell::new(None) };
}

/// The language in use (this thread's test override, if any).
pub fn current() -> Lang {
    OVERRIDE
        .with(Cell::get)
        .unwrap_or_else(|| Lang::from_u8(GLOBAL.load(Ordering::Relaxed)))
}

/// Changes the language for the whole process. Only startup and the user's language switch call this
/// (tests use [`with_lang`]).
pub fn set(lang: Lang) {
    GLOBAL.store(lang.to_u8(), Ordering::Relaxed);
}

pub fn is_en() -> bool {
    current() == Lang::En
}

/// Picks the side for the current language. Used by `tr!`.
pub fn pick<T>(ko: T, en: T) -> T {
    if is_en() { en } else { ko }
}

/// Text in both languages for constant tables (preset names, templates, theme names). Build it with `trp!`
/// and resolve it with [`Tr::get`] when drawing.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct Tr(pub &'static str, pub &'static str);

impl Tr {
    pub fn get(self) -> &'static str {
        pick(self.0, self.1)
    }

    /// For tests that check both languages (the UI uses `get`).
    #[cfg_attr(not(test), allow(dead_code))]
    pub fn ko(self) -> &'static str {
        self.0
    }

    #[cfg_attr(not(test), allow(dead_code))]
    pub fn en(self) -> &'static str {
        self.1
    }
}

/// Runs `f` with `lang` on this thread only and restores the previous language (also on panic).
#[cfg_attr(not(test), allow(dead_code))]
pub fn with_lang<R>(lang: Lang, f: impl FnOnce() -> R) -> R {
    struct Restore(Option<Lang>);
    impl Drop for Restore {
        fn drop(&mut self) {
            OVERRIDE.with(|o| o.set(self.0));
        }
    }
    let _restore = Restore(OVERRIDE.with(|o| o.replace(Some(lang))));
    f()
}

/// Fixed UI text: `tr!("Loaded")` -> `&'static str` in the current language. The Korean text comes from
/// `locales/ko*.json` at compile time (a missing entry is a compile error). Use `trf!` for placeholders.
macro_rules! tr {
    ($en:tt $(,)?) => {
        $crate::i18n::pick::<&'static str>(ko_text!($en), $en)
    };
}

/// Formatted UI text: `trf!("{n} items", n = n)` -> `String`, with `format!` arguments. Named placeholders
/// must be passed explicitly; both the English text and the Korean translation are checked by `format!`.
macro_rules! trf {
    ($en:tt $(, $($arg:tt)*)?) => {
        if $crate::i18n::is_en() {
            format!($en $(, $($arg)*)?)
        } else {
            format!(ko_text!($en) $(, $($arg)*)?)
        }
    };
}

/// Translation pair for constant tables (theme names, presets, templates): `trp!("Save")` -> [`Tr`].
macro_rules! trp {
    ($en:tt $(,)?) => {
        $crate::i18n::Tr(ko_text!($en), $en)
    };
}

// ---------- settings file ----------

/// User settings file: `CANDY_CORN_SETTINGS` if set (an empty value disables the settings file),
/// else `%APPDATA%\Candy-Corn\settings.json`.
pub fn settings_path() -> Option<PathBuf> {
    match std::env::var_os("CANDY_CORN_SETTINGS") {
        Some(p) if p.is_empty() => None,
        Some(p) => Some(PathBuf::from(p)),
        None => std::env::var_os("APPDATA").map(|d| PathBuf::from(d).join("Candy-Corn").join("settings.json")),
    }
}

/// Language saved in the settings file. None if the file is missing or broken.
pub fn load_saved(path: &Path) -> Option<Lang> {
    let text = std::fs::read_to_string(path).ok()?;
    let v: serde_json::Value = serde_json::from_str(text.trim_start_matches('\u{feff}')).ok()?;
    Lang::parse(v.get("lang")?.as_str()?)
}

/// Saves the language to the settings file, keeping other keys; writes a temp file and swaps it in.
pub fn save(path: &Path, lang: Lang) -> Result<(), String> {
    update(path, |v| v["lang"] = serde_json::json!(lang.code()))
}

/// Reads the settings file (a missing or broken file counts as an empty object), lets `edit` change it and writes it
/// back through a temp file, keeping the keys `edit` does not touch.
pub fn update(path: &Path, edit: impl FnOnce(&mut serde_json::Value)) -> Result<(), String> {
    let mut v = std::fs::read_to_string(path)
        .ok()
        .and_then(|t| serde_json::from_str::<serde_json::Value>(t.trim_start_matches('\u{feff}')).ok())
        .filter(serde_json::Value::is_object)
        .unwrap_or_else(|| serde_json::json!({}));
    edit(&mut v);
    if let Some(dir) = path.parent() {
        std::fs::create_dir_all(dir).map_err(|e| e.to_string())?;
    }
    let tmp = path.with_extension("json.tmp");
    let body = serde_json::to_string_pretty(&v).map_err(|e| e.to_string())?;
    std::fs::write(&tmp, body).map_err(|e| e.to_string())?;
    std::fs::rename(&tmp, path).map_err(|e| {
        let _ = std::fs::remove_file(&tmp);
        e.to_string()
    })
}
/// Saves the language to the default settings file (does nothing when the settings file is disabled).
pub fn save_default(lang: Lang) -> Result<(), String> {
    match settings_path() {
        Some(p) => save(&p, lang),
        None => Ok(()),
    }
}

/// Reads `--lang X` / `--lang=X` before clap parses the command line (needed to build the help in that
/// language). Returns None for an invalid value; clap reports the error.
pub fn lang_arg(args: &[OsString]) -> Option<Lang> {
    let mut it = args.iter().skip(1).map(|a| a.to_string_lossy());
    while let Some(a) = it.next() {
        if a == "--" {
            break;
        }
        if a == "--lang" {
            return it.next().and_then(|v| Lang::parse(&v));
        }
        if let Some(v) = a.strip_prefix("--lang=") {
            return Lang::parse(v);
        }
    }
    None
}

/// Startup language: command-line `--lang` > saved setting > English.
pub fn startup_lang(arg: Option<Lang>) -> Lang {
    arg.or_else(|| settings_path().and_then(|p| load_saved(&p)))
        .unwrap_or_default()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn tr_and_trf_follow_the_thread_language() {
        let n = 3;
        let rows = 7;
        with_lang(Lang::Ko, || {
            assert_eq!(tr!("Loaded"), ko_text!("Loaded"));
            assert_eq!(
                trf!("{n} constraints", n = n),
                format!(ko_text!("{n} constraints"), n = n)
            );
            assert_eq!(
                trf!("{1} of {0} rows", rows, n),
                format!(ko_text!("{1} of {0} rows"), rows, n)
            );
        });
        with_lang(Lang::En, || {
            assert_eq!(tr!("Loaded"), "Loaded");
            assert_eq!(trf!("{n} constraints", n = n), "3 constraints");
            assert_eq!(trf!("{1} of {0} rows", rows, n), "3 of 7 rows");
            // Nesting restores the outer language when the inner call ends
            with_lang(Lang::Ko, || assert!(!is_en()));
            assert!(is_en());
        });
    }

    #[test]
    fn default_language_is_english() {
        assert_eq!(Lang::default(), Lang::En);
        assert_eq!(Lang::from_u8(LANG_EN), Lang::En);
        // The process-wide default (tests never call `set`)
        assert_eq!(Lang::from_u8(GLOBAL.load(Ordering::Relaxed)), Lang::En);
    }

    #[test]
    fn with_lang_restores_after_panic() {
        let before = current();
        let r = std::panic::catch_unwind(|| with_lang(Lang::Ko, || panic!("x")));
        assert!(r.is_err());
        assert_eq!(current(), before);
    }

    #[test]
    fn tr_pairs_pick_by_language() {
        const T: Tr = trp!("Save");
        assert_eq!(with_lang(Lang::Ko, || T.get()), ko_text!("Save"));
        assert_eq!(with_lang(Lang::En, || T.get()), "Save");
        assert_eq!((T.ko(), T.en()), (ko_text!("Save"), "Save"));
    }

    #[test]
    fn parse_codes_and_names() {
        for (s, want) in [
            ("ko", Some(Lang::Ko)),
            ("KO", Some(Lang::Ko)),
            (ko_text!("Korean"), Some(Lang::Ko)),
            ("en", Some(Lang::En)),
            ("English", Some(Lang::En)),
            ("en-US", Some(Lang::En)),
            ("fr", None),
        ] {
            assert_eq!(Lang::parse(s), want, "{s}");
        }
        for l in Lang::ALL {
            assert_eq!(Lang::parse(l.code()), Some(l));
            assert_eq!(Lang::parse(l.native_name()), Some(l));
        }
    }

    #[test]
    fn lang_arg_reads_both_forms() {
        let a = |v: &[&str]| v.iter().map(OsString::from).collect::<Vec<_>>();
        assert_eq!(lang_arg(&a(&["exe", "--cli", "--lang", "en"])), Some(Lang::En));
        assert_eq!(lang_arg(&a(&["exe", "--lang=ko", "--cli"])), Some(Lang::Ko));
        assert_eq!(lang_arg(&a(&["exe", "--lang", "xx"])), None);
        assert_eq!(lang_arg(&a(&["exe", "--cli"])), None);
        // Nothing after `--` is an option
        assert_eq!(lang_arg(&a(&["exe", "--", "--lang", "en"])), None);
    }

    #[test]
    fn settings_round_trip_keeps_other_keys() {
        let dir = std::env::temp_dir().join(format!("cc_i18n_{}", std::process::id()));
        let path = dir.join("sub").join("settings.json");
        let _ = std::fs::remove_dir_all(&dir);
        assert_eq!(load_saved(&path), None);
        save(&path, Lang::Ko).unwrap();
        assert_eq!(load_saved(&path), Some(Lang::Ko));
        // Other keys (future settings) are kept, and a BOM is accepted
        std::fs::write(&path, "\u{feff}{\"lang\":\"ko\",\"other\":1}").unwrap();
        save(&path, Lang::En).unwrap();
        let v: serde_json::Value = serde_json::from_str(&std::fs::read_to_string(&path).unwrap()).unwrap();
        assert_eq!((v["lang"].as_str(), v["other"].as_i64()), (Some("en"), Some(1)));
        // A broken file is ignored and rewritten
        std::fs::write(&path, "{not json").unwrap();
        assert_eq!(load_saved(&path), None);
        save(&path, Lang::Ko).unwrap();
        assert_eq!(load_saved(&path), Some(Lang::Ko));
        let _ = std::fs::remove_dir_all(&dir);
    }
}

/// Source checks: Rust files contain no Hangul (Korean lives in locales/ and tests/fixtures/), and every
/// translation in the catalog is still used by some `tr!`/`trf!`/`trp!`/`ko_text!` call.
#[cfg(test)]
pub(crate) mod coverage {
    use std::collections::BTreeSet;
    use std::path::{Path, PathBuf};

    fn is_hangul(c: char) -> bool {
        matches!(
            c,
            '\u{AC00}'..='\u{D7A3}' | '\u{1100}'..='\u{11FF}' | '\u{3130}'..='\u{318F}' | '\u{A960}'..='\u{A97F}'
                | '\u{D7B0}'..='\u{D7FF}'
        )
    }

    fn root() -> &'static Path {
        Path::new(env!("CARGO_MANIFEST_DIR"))
    }

    /// Every Rust source of the package: src/, tests/ and build.rs.
    pub fn rust_files() -> Vec<PathBuf> {
        let mut files = vec![root().join("build.rs")];
        let mut stack = vec![root().join("src"), root().join("tests")];
        while let Some(d) = stack.pop() {
            let Ok(rd) = std::fs::read_dir(&d) else { continue };
            for e in rd.flatten() {
                let p = e.path();
                if p.is_dir() {
                    stack.push(p);
                } else if p.extension().is_some_and(|x| x == "rs") {
                    files.push(p);
                }
            }
        }
        files.sort();
        files
    }

    fn rel(p: &Path) -> String {
        p.strip_prefix(root()).unwrap_or(p).to_string_lossy().replace('\\', "/")
    }

    /// Lines with Hangul, as `file:line: text`, for files whose path contains one of `only` (all when empty).
    pub fn hangul_lines(only: &[&str]) -> Vec<String> {
        let mut out = vec![];
        for p in rust_files() {
            let rel = rel(&p);
            if !only.is_empty() && !only.iter().any(|o| rel.contains(o)) {
                continue;
            }
            let src = std::fs::read_to_string(&p).unwrap_or_default();
            for (i, line) in src.lines().enumerate() {
                if line.chars().any(is_hangul) {
                    out.push(format!("{rel}:{}: {}", i + 1, line.trim()));
                }
            }
        }
        out
    }

    /// Unescapes the body of a plain Rust string literal (the escapes build.rs writes).
    fn unescape(body: &str) -> String {
        let mut out = String::new();
        let mut it = body.chars().peekable();
        while let Some(c) = it.next() {
            if c != '\\' {
                out.push(c);
                continue;
            }
            match it.next() {
                Some('n') => out.push('\n'),
                Some('r') => out.push('\r'),
                Some('t') => out.push('\t'),
                Some('0') => out.push('\0'),
                Some('u') => {
                    let hex: String = it.by_ref().skip(1).take_while(|c| *c != '}').collect();
                    out.extend(u32::from_str_radix(&hex, 16).ok().and_then(char::from_u32));
                }
                Some(other) => out.push(other),
                None => {}
            }
        }
        out
    }

    /// Keys used as the first argument of `tr!`/`trf!`/`trp!`/`ko_text!` anywhere in the Rust sources.
    pub fn used_keys() -> BTreeSet<String> {
        let mut keys = BTreeSet::new();
        for p in rust_files() {
            let src = std::fs::read_to_string(&p).unwrap_or_default();
            for name in ["tr!(", "trf!(", "trp!(", "ko_text!("] {
                let mut rest = src.as_str();
                while let Some(at) = rest.find(name) {
                    let ident_before = rest[..at]
                        .chars()
                        .next_back()
                        .is_some_and(|c| c.is_alphanumeric() || c == '_');
                    rest = &rest[at + name.len()..];
                    if ident_before {
                        continue;
                    }
                    let Some(body) = rest.trim_start().strip_prefix('"') else {
                        continue;
                    };
                    let mut end = None;
                    let mut escaped = false;
                    for (k, c) in body.char_indices() {
                        match c {
                            _ if escaped => escaped = false,
                            '\\' => escaped = true,
                            '"' => {
                                end = Some(k);
                                break;
                            }
                            _ => {}
                        }
                    }
                    if let Some(e) = end {
                        keys.insert(unescape(&body[..e]));
                    }
                }
            }
        }
        keys
    }

    /// Keys of locales/ko.json and locales/ko.*.json.
    pub fn catalog_keys() -> BTreeSet<String> {
        let mut keys = BTreeSet::new();
        let Ok(rd) = std::fs::read_dir(root().join("locales")) else {
            return keys;
        };
        for e in rd.flatten() {
            let p = e.path();
            let name = p.file_name().and_then(|n| n.to_str()).unwrap_or("").to_string();
            if !(name == "ko.json" || (name.starts_with("ko.") && name.ends_with(".json"))) {
                continue;
            }
            let text = std::fs::read_to_string(&p).unwrap_or_default();
            if let Ok(serde_json::Value::Object(map)) = serde_json::from_str(text.trim_start_matches('\u{feff}')) {
                keys.extend(map.keys().filter(|k| !k.starts_with('_')).cloned());
            }
        }
        keys
    }

    fn filter() -> Vec<String> {
        std::env::var("I18N_ONLY")
            .unwrap_or_default()
            .split(',')
            .map(|s| s.trim().to_string())
            .filter(|s| !s.is_empty())
            .collect()
    }

    /// Rust sources must be English: Korean belongs in locales/ (UI text, linguistic data) and tests/fixtures/ (part of cargo test).
    /// `I18N_ONLY=app.rs,canvas/` limits the check to matching files.
    #[test]
    fn no_hangul_in_rust_sources() {
        let only = filter();
        let only: Vec<&str> = only.iter().map(String::as_str).collect();
        let found = hangul_lines(&only);
        let mut per_file: std::collections::BTreeMap<&str, usize> = Default::default();
        for m in &found {
            *per_file.entry(m.split(':').next().unwrap_or("")).or_default() += 1;
        }
        let summary: Vec<String> = per_file.iter().map(|(f, n)| format!("  {n:4} {f}")).collect();
        assert!(
            found.is_empty(),
            "{} lines with Hangul\n{}\n{}",
            found.len(),
            summary.join("\n"),
            found.iter().take(80).cloned().collect::<Vec<_>>().join("\n")
        );
    }

    /// Every catalog entry is still used (stale translations are removed when English text changes).
    #[test]
    fn every_translation_is_used() {
        let used = used_keys();
        let stale: Vec<String> = catalog_keys().into_iter().filter(|k| !used.contains(k)).collect();
        assert!(
            stale.is_empty(),
            "{} unused translations:\n{}",
            stale.len(),
            stale.join("\n")
        );
    }

    #[test]
    fn scanners_find_keys_and_hangul() {
        assert!(used_keys().contains("Loaded"));
        assert!(catalog_keys().contains("Loaded"));
        assert_eq!(unescape(r#"a\"b\\c\nd\u{2192}"#), "a\"b\\c\nd\u{2192}");
        assert!(is_hangul('\u{D55C}') && !is_hangul('A') && !is_hangul('\u{2192}'));
        // Fixtures: strings and arrays
        assert!(ko_fixture!("i18n.sample").chars().any(is_hangul));
        assert_eq!(ko_fixture!("i18n.list").len(), 2);
    }
}
